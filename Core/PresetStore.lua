--------------------------------------------------
-- Plugin states saved in the repository (Presets/), so that the HRC
-- presets created on one machine can be used on every machine.
--
-- One file per preset, named after the preset:
--
--     Presets/HRC_Bass_Bus_1176.lua
--
--     return {
--         preset = "HRC Bass Bus 1176",
--         plugin = "VST3: UADx 1176 Rev A Compressor",
--         fx_type = "VST3",
--         state = "<base64 plugin state>"
--     }
--
-- Files are written by ExportPresets.lua and read without access to any
-- library (empty environment): they can only return data.
--------------------------------------------------

local PresetStore = {}

local directory = nil

-- `path` ends with a directory separator. nil disables the store.
function PresetStore.SetDirectory(path)

    directory = path

end

function PresetStore.Directory()

    return directory

end

function PresetStore.FileName(preset)

    local name = preset:gsub("[^%w%-]+", "_")

    return name .. ".lua"

end

-- Returns the saved entry for `preset`, or nil.
function PresetStore.Load(preset)

    if not directory then
        return nil
    end

    local chunk = loadfile(directory .. PresetStore.FileName(preset), "t", {})

    if not chunk then
        return nil
    end

    local success, data = pcall(chunk)

    if not success or type(data) ~= "table" or type(data.state) ~= "string" or data.preset ~= preset then
        return nil
    end

    return data

end

-- Writes `entry` ({ preset, plugin, fx_type, state }). Returns the file
-- path, or nil and an error message.
function PresetStore.Save(entry)

    if not directory then
        return nil, "no preset directory"
    end

    local path = directory .. PresetStore.FileName(entry.preset)
    local file, message = io.open(path, "w")

    if not file then
        return nil, message
    end

    file:write("-- Generated by ExportPresets.lua: do not edit by hand.\n")
    file:write(string.format("return {\n    preset = %q,\n    plugin = %q,\n    fx_type = %q,\n    state = %q\n}\n",
        entry.preset, entry.plugin, entry.fx_type, entry.state))
    file:close()

    return path

end

return PresetStore
